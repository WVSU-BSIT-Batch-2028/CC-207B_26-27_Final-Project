import 'package:flutter/foundation.dart';

import 'activity.dart';

/// A play activity suggestion paired with a caregiver rationale.
@immutable
class Recommendation {
  /// Creates a [Recommendation].
  const Recommendation({
    required this.activityId,
    required this.title,
    required this.whyPicked,
    this.activity,
    this.isCustom = false,
  });

  /// Creates a [Recommendation] from a decoded JSON object.
  factory Recommendation.fromJson(Map<String, dynamic> json) {
    final activityId = json['activityId'] as String? ?? '';
    return Recommendation(
      activityId: activityId,
      title: json['title'] as String? ?? 'Suggested Activity',
      whyPicked: json['whyPicked'] as String? ?? '',
      activity: json['activity'] != null
          ? Activity.fromJson(json['activity'] as Map<String, dynamic>)
          : null,
      isCustom: json['isCustom'] == true || activityId.startsWith('custom-'),
    );
  }

  /// Identifier of the catalog activity referenced by this recommendation.
  final String activityId;

  /// Display title of the suggested play activity.
  final String title;

  /// Brief explanation of why the activity fits the caregiver's inputs.
  final String whyPicked;

  /// Full catalog activity details, when included in the API response.
  final Activity? activity;

  /// Whether this suggestion was custom-generated for caregiver materials
  /// rather than selected from the reviewed catalog.
  final bool isCustom;

  /// Serializes this [Recommendation] to a JSON map.
  Map<String, dynamic> toJson() {
    return {
      'activityId': activityId,
      'title': title,
      'whyPicked': whyPicked,
      if (activity != null) 'activity': activity!.toJson(),
      'isCustom': isCustom,
    };
  }
}

/// Response containing play suggestions and provenance metadata.
@immutable
class RecommendationResponse {
  /// Creates a [RecommendationResponse].
  const RecommendationResponse({
    required this.suggestions,
    required this.source,
    required this.tier,
    this.badge,
    this.label,
    required this.disclaimer,
    this.reviewed = true,
    this.materialNote,
  });

  /// Creates a [RecommendationResponse] from a decoded JSON object.
  factory RecommendationResponse.fromJson(Map<String, dynamic> json) {
    final rawSuggestions = json['suggestions'] as List<dynamic>? ?? [];
    final suggestions = rawSuggestions
        .map((e) => Recommendation.fromJson(e as Map<String, dynamic>))
        .toList();
    final provenance = json['provenance'] as Map<String, dynamic>?;

    return RecommendationResponse(
      suggestions: suggestions,
      source: json['source'] as String? ?? 'catalog_fallback',
      tier: (json['tier'] as num?)?.toInt() ?? 3,
      badge: provenance?['badge'] as String?,
      label: provenance?['label'] as String?,
      disclaimer:
          provenance?['disclaimer'] as String? ??
          'Observational play suggestion only. Not developmental assessment.',
      reviewed: provenance?['reviewed'] as bool? ?? true,
      materialNote: json['materialNote'] as String?,
    );
  }

  /// Suggested play activities returned for the request.
  final List<Recommendation> suggestions;

  /// Origin of the suggestions (`ai`, `ai_custom`, or `catalog_fallback`).
  final String source;

  /// Resolution tier used to produce the response (`1` for AI, `3` for fallback).
  final int tier;

  /// Optional disclosure badge displayed for AI-generated suggestions.
  final String? badge;

  /// Optional section label displayed for fallback or custom adaptation responses.
  final String? label;

  /// Non-diagnostic caregiver disclaimer accompanying the suggestions.
  final String disclaimer;

  /// Whether suggestions come directly from the reviewed catalog.
  final bool reviewed;

  /// Optional caregiver note explaining which entered materials were used or skipped.
  final String? materialNote;

  /// Whether this response was generated by the AI tier rather than a fallback.
  bool get isAiGenerated =>
      tier == 1 && (source == 'ai' || source == 'ai_custom') && badge != null;

  /// Whether this response contains custom material-adapted AI ideas rather
  /// than reviewed catalog entries.
  bool get isCustomGenerated => source == 'ai_custom';

  /// Serializes this [RecommendationResponse] to a JSON map.
  Map<String, dynamic> toJson() {
    return {
      'suggestions': suggestions.map((s) => s.toJson()).toList(),
      'source': source,
      'tier': tier,
      'provenance': {
        if (badge != null) 'badge': badge,
        if (label != null) 'label': label,
        'disclaimer': disclaimer,
        'reviewed': reviewed,
      },
      if (materialNote != null) 'materialNote': materialNote,
    };
  }
}

/// Supported adjustment options accepted by `POST /api/v1/ai/adapt`.
abstract final class ActivityAdjustments {
  /// Shortens the activity to fit a 5–10 minute window.
  static const String shorter = 'shorter';

  /// Simplifies the steps for an easier demonstration.
  static const String easier = 'easier';

  /// Adds an age-appropriate extra challenge.
  static const String harder = 'harder';

  /// Substitutes a missing household material safely.
  static const String missingMaterial = 'missing_material';
}

/// Adapted play activity returned by `POST /api/v1/ai/adapt`.
@immutable
class AdaptedActivity {
  /// Creates an [AdaptedActivity].
  const AdaptedActivity({
    required this.activityId,
    required this.originalTitle,
    required this.adaptedTitle,
    required this.adjustment,
    required this.instructions,
    required this.materials,
    required this.safetyNotice,
    required this.explanation,
    this.durationMinutes,
  });

  /// Creates an [AdaptedActivity] from a decoded JSON object.
  factory AdaptedActivity.fromJson(Map<String, dynamic> json) {
    final rawInstructions = json['instructions'] as List<dynamic>? ?? const [];
    final rawMaterials = json['materials'] as List<dynamic>? ?? const [];
    return AdaptedActivity(
      activityId: json['activityId'] as String? ?? '',
      originalTitle: json['originalTitle'] as String? ?? '',
      adaptedTitle:
          json['adaptedTitle'] as String? ??
          json['title'] as String? ??
          'Adapted activity',
      adjustment: json['adjustment'] as String? ?? ActivityAdjustments.shorter,
      instructions: rawInstructions.map((e) => e.toString()).toList(),
      materials: rawMaterials.map((e) => e.toString()).toList(),
      safetyNotice: json['safetyNotice'] as String? ?? '',
      explanation:
          json['explanation'] as String? ?? json['whyItWorks'] as String? ?? '',
      durationMinutes: (json['durationMinutes'] as num?)?.toInt(),
    );
  }

  /// Identifier of the source catalog activity.
  final String activityId;

  /// Title of the source catalog activity.
  final String originalTitle;

  /// Title of the adapted play variation.
  final String adaptedTitle;

  /// Adjustment mode applied to the activity.
  final String adjustment;

  /// Step-by-step instructions for the adapted variation.
  final List<String> instructions;

  /// Household materials used in the adapted variation.
  final List<String> materials;

  /// Supervision and safety reminder for the adapted variation.
  final String safetyNotice;

  /// Plain-language explanation of why the adaptation works.
  final String explanation;

  /// Optional adjusted duration in minutes.
  final int? durationMinutes;

  /// Builds a schedulable [Activity] snapshot derived from [base].
  Activity toActivity(Activity base) {
    final minutes =
        durationMinutes ??
        (adjustment == ActivityAdjustments.shorter ? 5 : base.durationMinutes);
    return Activity(
      id: 'custom-adapt-${base.id}',
      title: adaptedTitle,
      type: 'custom',
      language: base.language,
      setting: base.setting,
      ageBand: base.ageBand,
      domain: base.domain,
      durationMinutes: minutes,
      durationEstimate: '$minutes min',
      materials: materials,
      instructions: instructions.isNotEmpty ? instructions : base.instructions,
      provenanceSource: base.provenanceSource,
      status: Activity.statusSourceChecked,
      limitations: safetyNotice.isNotEmpty ? safetyNotice : base.limitations,
    );
  }

  /// Serializes this [AdaptedActivity] to a JSON map.
  Map<String, dynamic> toJson() {
    return {
      'activityId': activityId,
      'originalTitle': originalTitle,
      'adaptedTitle': adaptedTitle,
      'adjustment': adjustment,
      'instructions': instructions,
      'materials': materials,
      'safetyNotice': safetyNotice,
      'explanation': explanation,
      if (durationMinutes != null) 'durationMinutes': durationMinutes,
    };
  }
}

/// Response envelope returned by `POST /api/v1/ai/adapt`.
@immutable
class AdaptActivityResponse {
  /// Creates an [AdaptActivityResponse].
  const AdaptActivityResponse({
    required this.adapted,
    required this.source,
    required this.tier,
    this.badge,
    required this.disclaimer,
    this.model,
  });

  /// Creates an [AdaptActivityResponse] from a decoded JSON object.
  factory AdaptActivityResponse.fromJson(Map<String, dynamic> json) {
    final adaptedJson =
        json['adapted'] as Map<String, dynamic>? ?? const <String, dynamic>{};
    final provenance = json['provenance'] as Map<String, dynamic>?;
    return AdaptActivityResponse(
      adapted: AdaptedActivity.fromJson(adaptedJson),
      source: json['source'] as String? ?? 'fallback',
      tier: (json['tier'] as num?)?.toInt() ?? 2,
      badge: provenance?['badge'] as String?,
      disclaimer:
          provenance?['disclaimer'] as String? ??
          'Everyday play idea only — not a medical or developmental test.',
      model: provenance?['model'] as String?,
    );
  }

  /// Adapted activity details returned by the API.
  final AdaptedActivity adapted;

  /// Origin of the adaptation (`ai` or `fallback`).
  final String source;

  /// Resolution tier (`1` for AI, `2` for deterministic rule-based fallback).
  final int tier;

  /// Optional AI disclosure badge.
  final String? badge;

  /// Non-diagnostic disclaimer accompanying the adaptation.
  final String disclaimer;

  /// Optional model identifier used on the server.
  final String? model;

  /// Whether this adaptation was generated by the AI tier rather than fallback.
  bool get isAiGenerated => tier == 1 && source == 'ai' && badge != null;

  /// Serializes this [AdaptActivityResponse] to a JSON map.
  Map<String, dynamic> toJson() {
    return {
      'adapted': adapted.toJson(),
      'source': source,
      'tier': tier,
      'provenance': {'badge': badge, 'disclaimer': disclaimer, 'model': model},
    };
  }
}
